#!/usr/bin/env python3
"""Generate or check README.crates.md, the README that crates.io shows.

crates.io drops <picture>/<source> and keeps only the <img>, and it renders
mermaid blocks with mermaid's light theme even on its dark theme. So this
copy of README.md:

- replaces each <picture> with its <img>, pointed at the image's `-auto`
  variant when one exists (`foo-light.svg` or `foo.svg` -> `foo-auto.svg`):
  an SVG that follows the viewer's theme by itself (tools/adaptive_svg.py);
- replaces each mermaid block with the SVG listed in MERMAID, in order
  (generated by tools/readme_diagrams.py).
"""

from __future__ import annotations

import argparse
import pathlib
import re


ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "README.md"
OUTPUT = ROOT / "README.crates.md"

PICTURE = re.compile(r"[ \t]*<picture>.*?(<img\b[^>]*>).*?</picture>", re.DOTALL)
IMG_SRC = re.compile(r'src="([^"]+)"')
MERMAID_BLOCK = re.compile(r"```mermaid\n.*?\n```", re.DOTALL)
# Stand-ins for README.md's mermaid blocks, in order: (path, alt text).
MERMAID = [
    (
        "docs/assets/evidence-tiers.svg",
        "Evidence tiers: observe the key itself (whykey listen); if it is not "
        "observable, ask the running program; if it cannot be asked, read "
        "configuration files and built-in defaults.",
    ),
    (
        "docs/assets/reality-lab.svg",
        "A reality-lab scenario starts the real program, presses a synthetic key, "
        "and lets an independent oracle record what happened; it passes only if "
        "whykey's verdict matches that ground truth.",
    ),
]
HEADER = (
    "<!-- Generated from README.md by tools/generate_crates_readme.py. "
    "Do not edit it by hand; CI checks that it is current. -->\n\n"
)


def render() -> str:
    source = SOURCE.read_text(encoding="utf-8")

    def adaptive_img(match: re.Match[str]) -> str:
        indent = match.group(0)[: len(match.group(0)) - len(match.group(0).lstrip())]
        return indent + IMG_SRC.sub(auto_variant, match.group(1), count=1)

    blocks = MERMAID_BLOCK.findall(source)
    if len(blocks) != len(MERMAID):
        raise SystemExit(
            f"README.md has {len(blocks)} mermaid blocks but MERMAID lists "
            f"{len(MERMAID)} stand-ins; update tools/generate_crates_readme.py"
        )
    stand_ins = iter(MERMAID)

    def mermaid_img(_: re.Match[str]) -> str:
        path, alt = next(stand_ins)
        return f'<p align="center">\n  <img src="{path}" alt="{alt}" width="820">\n</p>'

    return HEADER + MERMAID_BLOCK.sub(mermaid_img, PICTURE.sub(adaptive_img, source))


def auto_variant(match: re.Match[str]) -> str:
    path = match.group(1)
    stem = path.removesuffix(".svg").removesuffix("-light")
    auto = f"{stem}-auto.svg"
    return f'src="{auto}"' if (ROOT / auto).exists() else match.group(0)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != expected:
            print(f"{OUTPUT.name} is stale; run tools/generate_crates_readme.py")
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
